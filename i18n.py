def ui_lang() -> str:
    return st.session_state.get("ui_lang", "ar")


def t(key: str) -> str:
    table = _AR if ui_lang() == "ar" else _EN
    return table.get(key, key)


def status_label(status: str) -> str:
    lang = ui_lang()
    mapping_ar = {
        "confirmed": "مؤكد",
        "pending": "في انتظار التأكيد",
        "cancelled": "ملغى",
        "completed": "اكتمل",
        "late": "متأخر",
    }
    mapping_en = {
        "confirmed": "Confirmed",
        "pending": "Pending",
        "cancelled": "Cancelled",
        "completed": "Completed",
        "late": "Late",
    }
    m = mapping_ar if lang == "ar" else mapping_en
    return m.get(status, status)
